export interface HeadRect {
  x: number;
  y: number;
  w: number;
  color: string;
}

export interface HeadDesign {
  id: string;
  name: string;
  // Victorias necesarias para desbloquearlo. 0 = siempre desbloqueado.
  winsRequired: number;
  // Colores FIJOS de este gorro puntual — a diferencia del detective
  // original (que se recolorea según el skin de color activo), estos
  // diseños coleccionables tienen su propia identidad visual siempre.
  hatColor: string;
  bandColor: string;
  // Opcional: color de la frente (la franja justo debajo de la copa del
  // gorro). Por defecto es el crema fijo de siempre — pero si el gorro
  // es blanco o muy claro (como el de Chef), esa frente crema casi no se
  // distingue del gorro y se pierde la silueta. Para esos casos puntuales
  // se puede pisar con un tono apenas más oscuro, sin tener que inventar
  // toda una paleta nueva.
  foreheadColor?: string;
  // Si se define, IGNORA todo lo de arriba (salvo winsRequired/name/id) y
  // dibuja esta lista de rectángulos en su lugar — para diseños que
  // cambian la silueta entera (Alien, Spaceman, Auriculares), no solo
  // "un gorro arriba de la misma cara de siempre".
  customRects?: HeadRect[];
}

