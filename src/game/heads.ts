export function getHeadDesign(id: string): HeadDesign {
  return HEAD_DESIGNS.find((h) => h.id === id) ?? HEAD_DESIGNS[0];
}

export function getUnlockedHeads(wins: number): HeadDesign[] {
  return HEAD_DESIGNS.filter((h) => wins >= h.winsRequired);
}
